import io
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from reportlab.pdfgen import canvas

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_elements(num_pages)
            super().showPage()
        super().save()

    def draw_page_elements(self, page_count):
        self.saveState()
        
        footer_text = getattr(self, 'proposal_footer_text', 'Generated by AI WorksForYou')
        
        # Suppress running header on Page 1
        if self._pageNumber > 1:
            self.setStrokeColor(colors.HexColor('#e2e8f0'))
            self.setLineWidth(0.5)
            self.line(36, 756, 576, 756)
            
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(colors.HexColor('#94a3b8'))
            self.drawString(36, 762, "AI AUTOMATION QUOTATION")
        
        # Running Page footer
        self.setStrokeColor(colors.HexColor('#e2e8f0'))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45)
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#64748b'))
        
        # Draw footer notice
        self.drawString(36, 30, footer_text)
        
        # Draw page counter
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(576, 30, page_str)
        self.restoreState()


class PDFService:
    def _normalize_packages(self, raw_packages):
        """Normalizes dynamic packages list or dictionary for PDF compiler."""
        if isinstance(raw_packages, list):
            return raw_packages
        if isinstance(raw_packages, dict):
            normalized = []
            for name, val in raw_packages.items():
                if isinstance(val, dict):
                    normalized.append({
                        "name": name,
                        "price": val.get("price") or "Contact Sales",
                        "description": val.get("description") or ", ".join(val.get("features", []))
                    })
            return normalized
        return []

    def generate_proposal_pdf(self, proposal_data, company_settings=None):
        """
        Generates a minimal 1-2 page quotation PDF in business-first order:
        About Company -> Client Details & Requirement -> Our Solution -> Services -> Benefits -> Pricing -> Why Choose Us -> CTA.
        """
        buffer = io.BytesIO()
        
        # Margins to maximize printing surface and keep strictly within 1-2 pages
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=45,
            bottomMargin=55
        )
        
        # Extract branding details from canonical companyProfile
        profile = proposal_data.get("companyProfile", {}) or {}
        company_name = profile.get("companyName", "GDS MEDIA")
        brand_name = profile.get("brandName", "AI WORKSFORYOU")
        company_email = profile.get("email", "")
        company_phone = profile.get("phone", "")
        company_website = profile.get("website", "")
        
        # Color palettes
        brand_colors = profile.get("brandColors", {}) or {}
        primary_hex = brand_colors.get("primary", "#2563eb")
        secondary_hex = brand_colors.get("secondary", "#0f172a")
        
        primary_color = colors.HexColor(primary_hex)
        secondary_color = colors.HexColor(secondary_hex)
        text_dark = colors.HexColor('#1e293b')
        border_light = colors.HexColor('#cbd5e1')
        bg_light = colors.HexColor('#f8fafc')
        
        # Setup styles
        styles = getSampleStyleSheet()
        
        h1_style = ParagraphStyle(
            name='QuotationH1',
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=14,
            textColor=primary_color,
            spaceBefore=8,
            spaceAfter=4,
            keepWithNext=True
        )

        body_style = ParagraphStyle(
            name='QuotationBody',
            fontName='Helvetica',
            fontSize=9,
            leading=13,
            textColor=text_dark,
            spaceAfter=4
        )

        story = []

        # Extract content sections strictly from canonical keys
        about_company = proposal_data.get("aboutCompany", "")
        understanding = proposal_data.get("understanding", "")
        solution = proposal_data.get("proposedSolution", "")
        services = proposal_data.get("servicesIncluded", [])
        benefits = proposal_data.get("businessBenefits", [])
        why_us = proposal_data.get("whyUs", "")
        cta = proposal_data.get("cta", "")
        
        # 1. Minimal Header
        header_left_html = (
            f"<font size=15 color='{primary_hex}'><b>{brand_name.upper() if brand_name else company_name.upper()}</b></font><br/>"
        )
        if brand_name:
            header_left_html += f"<font size=8.5 color='#64748b'>Powered by {company_name}</font>"
            
        contact_lines = []
        if company_email: contact_lines.append(f"Email: {company_email}")
        if company_phone: contact_lines.append(f"Phone: {company_phone}")
        if company_website: contact_lines.append(f"Web: {company_website.replace('https://','').replace('http://','')}")
        
        header_right_html = "<br/>".join([f"<font size=8 color='#475569'>{line}</font>" for line in contact_lines])
        
        header_table = Table(
            [[Paragraph(header_left_html, styles['Normal']), Paragraph(header_right_html, ParagraphStyle('HeaderRight', alignment=2))]],
            colWidths=[270, 270]
        )
        header_table.setStyle(TableStyle([
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
            ('BOTTOMPADDING', (0,0), (-1,-1), 8),
            ('LINEBELOW', (0,0), (-1,-1), 1.5, primary_color),
        ]))
        story.append(header_table)
        story.append(Spacer(1, 8))

        # 2. Section 1: About Our Company
        story.append(Paragraph("About Our Company", h1_style))
        story.append(Paragraph(about_company, body_style))
        story.append(Spacer(1, 4))

        # 3. Section 2: Client Details & Requirement (Restated)
        client_name = proposal_data.get("clientContactName", "N/A")
        client_company = proposal_data.get("clientBusinessName", "N/A")
        client_industry = proposal_data.get("industry", "N/A")
        client_email = proposal_data.get("email", "")
        client_phone = proposal_data.get("phone", "")
        
        client_lines = [
            f"<b>Client Representative:</b> {client_name}",
            f"<b>Company Name:</b> {client_company}",
            f"<b>Industry Vertical:</b> {client_industry}"
        ]
        if client_email:
            client_lines.append(f"<b>Email:</b> {client_email}")
        if client_phone:
            client_lines.append(f"<b>Phone:</b> {client_phone}")
            
        client_html = "<br/>".join(client_lines)
        
        req_html = (
            f"<b>Quoted Need:</b><br/>"
            f"{understanding}"
        )
        
        client_table = Table(
            [[Paragraph(client_html, body_style), Paragraph(req_html, body_style)]],
            colWidths=[230, 310]
        )
        client_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), bg_light),
            ('BOX', (0,0), (-1,-1), 0.5, border_light),
            ('PADDING', (0,0), (-1,-1), 8),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ]))
        
        story.append(Paragraph("Client Requirement", h1_style))
        story.append(client_table)
        story.append(Spacer(1, 8))

        # 4. Section 3: Our Proposed Solution
        story.append(Paragraph("Our Proposed Solution", h1_style))
        story.append(Paragraph(solution, body_style))
        story.append(Spacer(1, 4))

        # 5. Section 4 & 5: Services Included & Benefits (Side by side)
        services_html = "<b>Services Included:</b><br/>" + "<br/>".join([f"• {s}" for s in services])
        benefits_html = "<b>Business Benefits:</b><br/>" + "<br/>".join([f"• {b}" for b in benefits])
        
        sb_table = Table(
            [[Paragraph(services_html, body_style), Paragraph(benefits_html, body_style)]],
            colWidths=[270, 270]
        )
        sb_table.setStyle(TableStyle([
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('LINEAFTER', (0,0), (0,-1), 0.5, border_light),
            ('RIGHTPADDING', (0,0), (0,-1), 10),
            ('LEFTPADDING', (1,0), (1,-1), 10),
            ('BOTTOMPADDING', (0,0), (-1,-1), 2),
        ]))
        
        story.append(KeepTogether([
            Paragraph("Scope of Automation & Benefits", h1_style),
            sb_table
        ]))
        story.append(Spacer(1, 8))

        # 6. Section 6: Pricing Packages (Dynamic Table)
        packages_list = proposal_data.get("pricingPackages", [])
        pricing_data = [
            ["Pricing Package", "Investment Fee", "Description"]
        ]
        
        for pkg in packages_list:
            name = pkg.get("name") or "Quoted Deal"
            price = pkg.get("price") or "Contact Sales"
            desc = pkg.get("description") or "Implementation scoped details"
            pricing_data.append([
                Paragraph(f"<b>{name}</b>", body_style),
                Paragraph(f"<b>{price}</b>", body_style),
                Paragraph(desc, body_style)
            ])
        
        pricing_table = Table(pricing_data, colWidths=[150, 140, 250])
        pricing_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), secondary_color),
            ('TEXTCOLOR', (0,0), (-1,0), colors.white),
            ('ALIGN', (0,0), (-1,-1), 'LEFT'),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('GRID', (0,0), (-1,-1), 0.5, border_light),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('PADDING', (0,0), (-1,-1), 6),
        ]))
        
        pricing_blocks = [
            Paragraph("Monthly Investment Packages", h1_style),
            pricing_table
        ]
        story.append(KeepTogether(pricing_blocks))
        story.append(Spacer(1, 8))

        # 7. Section 7 & 8: Why Choose Us & Call To Action
        why_cta_html = (
            f"<b>Why Choose Us?</b><br/>"
            f"{why_us}<br/><br/>"
            f"<font size=9.5 color='{primary_hex}'><b>Next Step / Call to Action:</b></font><br/>"
            f"<b>{cta}</b>"
        )
        
        why_cta_table = Table([[Paragraph(why_cta_html, body_style)]], colWidths=[540])
        why_cta_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), bg_light),
            ('BOX', (0,0), (-1,-1), 1, primary_color),
            ('PADDING', (0,0), (-1,-1), 8),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ]))
        story.append(KeepTogether([why_cta_table]))

        # Build PDF using NumberedCanvas
        def setup_canvas_meta(canvas_inst, doc_inst):
            canvas_inst.proposal_footer_text = "Generated by AI WorksForYou"
            canvas_inst.primary_color_hex = primary_hex
            
        doc.build(
            story,
            canvasmaker=NumberedCanvas,
            onFirstPage=lambda c, d: setup_canvas_meta(c, d),
            onLaterPages=lambda c, d: setup_canvas_meta(c, d)
        )
        
        buffer.seek(0)
        return buffer.getvalue()
